import {get,post,patch} from '../../shared/api.js';
const root='v9/crops';
export const metadata=()=>get(`${root}/meta`);
export const workspace=()=>get(`${root}/workspace`);
export const dueRoutines=day=>get(`${root}/routines/due?day=${encodeURIComponent(day)}`);
export const addProject=data=>post(`${root}/projects`,data);
export const addField=data=>post('v6/crops/fields',data);
export const addUnit=data=>post(`${root}/units`,data);
export const addVariety=data=>post(`${root}/varieties`,data);
export const addCycle=data=>post(`${root}/cycles`,data);
export const addBudget=data=>post(`${root}/budgets`,data);
export const addRoutine=data=>post(`${root}/routines`,data);
export const finishRoutine=(id,data)=>post(`${root}/routines/${id}/complete`,data);
export const addTrial=data=>post(`${root}/trials`,data);
export const addPlot=data=>post(`${root}/plots`,data);
export const addRecord=(section,data)=>post(`${root}/records/${section}`,data);
export const addHarvest=data=>post(`${root}/harvest`,data);
export const addStock=data=>post(`${root}/stock`,data);
export const addSale=data=>post(`${root}/sales`,data);
export const updateProjectStatus=(id,status)=>patch(`${root}/projects/${id}/status`,{status});
export const updateCycleStatus=(id,status)=>patch(`${root}/cycles/${id}/status`,{status});
export const updateTrialStatus=(id,status)=>patch(`${root}/trials/${id}/status`,{status});
export const getAnalytics=()=>get(`${root}/analytics`);
